#!/usr/bin/env python3
"""Install VideoFake deps on current Google Colab (Python 3.12+/3.13, CUDA 12/13)."""

from __future__ import annotations

import glob
import os
import pathlib
import shutil
import subprocess
import sys
import site


def run(cmd: list[str], env: dict | None = None) -> None:
    print("+", " ".join(cmd), flush=True)
    subprocess.check_call(cmd, env=env)


def pip_install(*args: str, env: dict | None = None) -> None:
    run([sys.executable, "-m", "pip", "install", "-q", *args], env=env)


def patch_setup_get_version(setup_py: pathlib.Path) -> None:
    """Fix Python 3.13: exec() no longer populates locals() in get_version()."""
    if not setup_py.exists():
        return
    text = setup_py.read_text(encoding="utf-8")
    old = (
        "def get_version():\n"
        "    with open(version_file, 'r') as f:\n"
        "        exec(compile(f.read(), version_file, 'exec'))\n"
        "    return locals()['__version__']"
    )
    new = (
        "def get_version():\n"
        "    with open(version_file, 'r') as f:\n"
        "        _d = {}\n"
        "        exec(compile(f.read(), version_file, 'exec'), _d)\n"
        "    return _d['__version__']"
    )
    if old in text:
        setup_py.write_text(text.replace(old, new), encoding="utf-8")
        print(f"Patched get_version in {setup_py}", flush=True)
    elif "return locals()['__version__']" in text:
        setup_py.write_text(
            text.replace("return locals()['__version__']", "return _d['__version__']").replace(
                "exec(compile(f.read(), version_file, 'exec'))",
                "_d = {}\n        exec(compile(f.read(), version_file, 'exec'), _d)",
            ),
            encoding="utf-8",
        )
        print(f"Patched get_version (fallback) in {setup_py}", flush=True)


def clone(url: str, dest: pathlib.Path) -> None:
    if dest.exists():
        print(f"Already cloned: {dest}", flush=True)
        return
    run(["git", "clone", "--depth", "1", url, str(dest)])


def install_local_no_deps(dest: pathlib.Path) -> None:
    """Install package without pulling tb-nightly/torch/etc. (those hang on Colab)."""
    patch_setup_get_version(dest / "setup.py")
    env = os.environ.copy()
    # Skip CUDA op compilation — not needed for GFPGAN face enhance
    env["BASICSR_EXT"] = "False"
    env["FORCE_CUDA"] = "0"
    pip_install(
        "--no-deps",
        "--no-build-isolation",
        str(dest),
        env=env,
    )


def patch_torchvision_basicsr() -> None:
    old = "from torchvision.transforms.functional_tensor import rgb_to_grayscale"
    new = "from torchvision.transforms.functional import rgb_to_grayscale"
    patterns = [
        "/usr/local/lib/python*/dist-packages/basicsr/data/degradations.py",
        "/content/BasicSR/basicsr/data/degradations.py",
        str(pathlib.Path(site.getsitepackages()[0]) / "basicsr" / "data" / "degradations.py"),
    ]
    for pattern in patterns:
        for path in glob.glob(pattern):
            p = pathlib.Path(path)
            if not p.exists():
                continue
            text = p.read_text(encoding="utf-8")
            if old in text:
                p.write_text(text.replace(old, new), encoding="utf-8")
                print("Patched torchvision import:", path, flush=True)


def ensure_basicsr_version_file(repo: pathlib.Path) -> None:
    """basicsr needs version.py generated by setup; create a minimal one if missing."""
    version_py = repo / "basicsr" / "version.py"
    if version_py.exists():
        return
    version_py.write_text(
        "# Generated for Colab install\n"
        "__version__ = '1.4.2'\n"
        "short_version = '1.4.2'\n"
        "version_info = (1, 4, 2)\n",
        encoding="utf-8",
    )
    print(f"Wrote {version_py}", flush=True)


def main() -> None:
    root = pathlib.Path(__file__).resolve().parent
    print("Python:", sys.version, flush=True)

    print("\n=== 1/3 Core packages ===", flush=True)
    # Force ORT 1.19.x (newer builds hit cuDNN Frontend HEURISTIC_QUERY_FAILED on T4)
    pip_install("--force-reinstall", "--no-deps", "onnxruntime-gpu==1.19.2")
    pip_install("-r", str(root / "requirements-colab.txt"))

    print("\n=== 2/3 face_enhancer deps (no heavy transitive installs) ===", flush=True)
    basicsr_dir = pathlib.Path("/content/BasicSR")
    facexlib_dir = pathlib.Path("/content/facexlib")

    clone("https://github.com/XPixelGroup/BasicSR.git", basicsr_dir)
    ensure_basicsr_version_file(basicsr_dir)
    install_local_no_deps(basicsr_dir)

    clone("https://github.com/xinntao/facexlib.git", facexlib_dir)
    install_local_no_deps(facexlib_dir)

    # Lightweight runtime deps only (skip tb-nightly — that is what hangs)
    pip_install("addict", "yapf", "lmdb", "future", "filterpy")
    pip_install("--no-deps", "gfpgan==1.3.8")

    print("\n=== 3/3 Patches + checks ===", flush=True)
    patch_torchvision_basicsr()

    import onnxruntime as ort

    print("onnxruntime:", ort.__version__, flush=True)
    print("providers:", ort.get_available_providers(), flush=True)
    if "CUDAExecutionProvider" not in ort.get_available_providers():
        print("WARNING: CUDAExecutionProvider missing — face swap may fall back to CPU.", flush=True)

    try:
        import basicsr  # noqa: F401
        import gfpgan  # noqa: F401

        print("gfpgan/basicsr: OK", flush=True)
    except Exception as exc:
        print("WARNING: face_enhancer deps incomplete:", exc, flush=True)
        print("You can still run with Processor = face_swapper only.", flush=True)

    print("\nInstall finished.", flush=True)


if __name__ == "__main__":
    main()
